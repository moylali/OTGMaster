#!/usr/bin/env bash
# Regenerates app/src/test/resources/veracrypt/keyfiles/: VeraCrypt volumes made with
# keyfiles, by VeraCrypt itself, for VeraCryptKeyfilesTest (docs/TEST_DATA.md).
#
#   scripts/make_veracrypt_keyfile_fixtures.sh    # needs veracrypt on PATH; no root
#
# Same 1024-byte cut as make_veracrypt_fixtures.sh: the header sector, then the first data
# sector (a FAT boot sector). AES / SHA-512 / PIM 1 throughout; what varies is how the
# keyfiles meet the password, which is the part VeraCrypt specifies and we reimplement:
#   empty_2kf   no password, keyfiles A and B  (B is past 1 MiB: only its first MiB counts)
#   pw40_2kf    a 40-character password, keyfiles A and B  (64-byte pool)
#   pw70_1kf    a 70-character password, keyfile A  (over 64 bytes: the 128-byte pool)
# The keyfiles are not stored: keyfile(seed, size) below is regenerated by the test, so the
# repo holds 3 KiB instead of a megabyte of noise.
set -euo pipefail
cd "$(dirname "$0")/.."
out=app/src/test/resources/veracrypt/keyfiles
command -v veracrypt >/dev/null || { echo "veracrypt not on PATH" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$out"

# Byte i of keyfile(seed, size) is (i * 31 + seed * 7 + (i >> 9)) mod 251; the test has the same formula.
keyfile() { python3 -c "import sys; s,n=int(sys.argv[1]),int(sys.argv[2]); sys.stdout.buffer.write(bytes((i*31+s*7+(i>>9))%251 for i in range(n)))" "$1" "$2"; }
keyfile 1 300 > "$tmp/A.key"
keyfile 2 1100000 > "$tmp/B.key"

make() {  # name password keyfiles
    vol="$tmp/$1.hc"
    veracrypt --text --non-interactive --create "$vol" --size=2M --volume-type=normal \
        --encryption=AES --hash=SHA-512 --filesystem=fat --password="$2" --pim=1 --keyfiles="$3" \
        --random-source=/dev/urandom </dev/null >/dev/null
    { dd if="$vol" bs=512 count=1 status=none; dd if="$vol" bs=512 skip=256 count=1 status=none; } > "$out/$1.bin"
    echo "$out/$1.bin"
}
make empty_2kf "" "$tmp/A.key,$tmp/B.key"
make pw40_2kf "$(printf 'k%.0s' $(seq 40))" "$tmp/A.key,$tmp/B.key"
make pw70_1kf "$(printf 'K%.0s' $(seq 70))" "$tmp/A.key"
veracrypt --text --version > "$out/VERSION"
